/**
 * The drink lineup.
 *
 * MindAR is a PLANAR tracker and a can is a cylinder, so one photo only matches
 * while the can is turned roughly as it was photographed (~±30-40°). Each can
 * therefore carries several photos taken around it, and every one of them
 * resolves back to the same drink.
 *
 * INVARIANT: the MindAR target index is the index into `targetEntries` — the
 * flattened list of every photo of every can, in array order.
 * `scripts/compileTargets.ts` compiles them in exactly that order, so
 * reordering `cans` or a can's `targetImages` without recompiling silently
 * pairs cans with the wrong 3D model. Add new cans and new angles at the END.
 *
 * Photos live in `public/targets/<id>/` so one file serves as both the tracking
 * target (read from disk by the compiler) and the label texture wrapped around
 * the 3D can (fetched by the browser). Set `labelTexture` only if you have a
 * proper flat label unwrap that differs from the tracking photos.
 */

export type Can = {
  /** stable slug, used as a react key and in logs */
  id: string
  /**
   * Photos taken around the can, paths under public/targets (e.g.
   * 'pepsi/wrap-01.jpg'). ALL of them map back to this can. More angles means
   * more rotation coverage and a longer compile — 4 to 6 covers a can well.
   */
  targetImages: string[]
  name: string
  flavour: string
  calories: number
  volumeMl: number
  /** optional override; defaults to the first target image */
  labelTexture?: string
  /** aluminium tint for the top/bottom, and the fallback body colour */
  bodyColor: string
  /**
   * Model height as a multiple of the target image width. MindAR normalises a
   * target's width to 1 unit, so this is how you dial the can to sit exactly
   * on the real one. Start at 1 and tune by eye.
   */
  scale: number
}

