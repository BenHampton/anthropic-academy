/** directory holding target photos, relative to the project root */
export const targetsDir = 'public/targets'

export type TargetEntry = {
  can: Can
  /** path under public/targets, e.g. 'pepsi/wrap-01.jpg' */
  image: string
  /** which angle of that can this is, 1-based, for human-readable output */
  angle: number
}

/**
 * Every photo of every can, flattened. THIS is the compile order, and an
 * index into this array is a MindAR target index. Many entries map to one can.
 */
export const targetEntries: TargetEntry[] = cans.flatMap((can) =>
  can.targetImages.map((image, i) => ({ can, image, angle: i + 1 }))
)

/** browser-facing url for a can's label texture */
export const labelTextureUrl = (can: Can) =>
  `/targets/${can.labelTexture ?? can.targetImages[0] ?? ''}`

/** project-relative path the compiler script reads from disk */
export const targetImagePath = (image: string) => `${targetsDir}/${image}`

export const canByTargetIndex = (index: number): Can | undefined => targetEntries[index]?.can
